#!/usr/bin/env python3
"""Differential campaign over random Cairo integer programs.

    benchmarks/differential/run_arith.py --uc target/release/uc --out <dir> \
        [--packages 20] [--functions 50] [--cases 8] [--seed 1] [--snforge] [--scarb] [--prove 300]

For every generated function the Python semantics in arith_gen.py decide, per input, whether
the call returns (and what) or panics. Each case becomes a `#[test]` (`assert` on the value) or a
`#[should_panic]` test. Then:

* `uc test` must pass every case (a failure is a disagreement with the reference semantics);
* `snforge test` (with --snforge) runs the same package; a case where uc and snforge differ is a
  uc or snforge bug, a case where both differ from Python is a generator bug;
* `scarb build` (with --scarb) must produce byte-identical artifacts to `uc build`;
* `uc prove` (with --prove N) checks N extra functions over `u8` (plus helpers they call) against brute force:
  PROVEN_SAFE on a function with a reachable panic is a soundness bug, a COUNTEREXAMPLE_FOUND
  whose witness does not panic is a false positive.

A JSON summary and every disagreement go to <out>/summary.json.
"""
import argparse
import hashlib
import itertools
import json
import os
import random
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from arith_gen import Function, TYPES, prelude, rand_value  # noqa: E402

MANIFEST = """[package]
name = "{name}"
version = "0.1.0"
edition = "2024_07"

[dependencies]
starknet = "2.18.0"

[dev-dependencies]
snforge_std = "0.60.0"

[[target.starknet-contract]]
sierra = true
casm = true

[scripts]
test = "snforge test"

[tool.scarb]
allow-prebuilt-plugins = ["snforge_std"]
"""


def cairo_value(v, ty):
    return f"{v}_{ty}"


def write_package(root, name, functions, cases):
    (root / "src").mkdir(parents=True, exist_ok=True)
    (root / "Scarb.toml").write_text(MANIFEST.format(name=name))
    body = ["// generated by benchmarks/differential/run_arith.py", prelude()]
    for f in functions:
        body.append(f.cairo())
    # A contract exposing a few functions so build parity also covers contract classes.
    exposed = functions[: min(8, len(functions))]
    body.append("#[starknet::contract]\npub mod Exposed {\n    #[storage]\n    struct Storage {}")
    for f in exposed:
        params = ", ".join(f"{p}: {f.ty}" for p in f.params)
        call = ", ".join(f.params)
        body.append(f"    #[external(v0)]\n    fn call_{f.name}(self: @ContractState, {params}) -> {f.ty} {{ super::{f.name}({call}) }}")
    body.append("}")
    tests = ["#[cfg(test)]\nmod tests {"]
    for (fname, idx, args, outcome, ty) in cases:
        call = f"super::{fname}({', '.join(cairo_value(a, ty) for a in args)})"
        tname = f"t_{fname}_{idx}"
        if outcome[0] == "ok":
            tests.append(f"    #[test]\n    fn {tname}() {{\n        assert({call} == {cairo_value(outcome[1], ty)}, 'value mismatch');\n    }}")
        else:
            tests.append(f"    #[test]\n    #[should_panic]\n    fn {tname}() {{\n        let _x = {call};\n    }}")
    tests.append("}")
    (root / "src" / "lib.cairo").write_text("\n\n".join(body + ["\n".join(tests)]) + "\n")


def run(cmd, cwd, timeout=1800, env=None):
    t0 = time.perf_counter()
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout, env=env)
    return p, time.perf_counter() - t0


def uc_test_verdicts(uc, pkg):
    p, secs = run([uc, "test", "--json"], pkg)
    out = p.stdout
    try:
        rep = json.loads(out[out.index("{"):])
    except ValueError:
        return None, secs, (p.stderr or p.stdout)[-2000:]
    return {t["name"].split("::")[-1]: t["status"] for t in rep.get("tests", [])}, secs, None


def snforge_verdicts(pkg):
    env = dict(os.environ, SCARB_OFFLINE="true")
    p, secs = run(["snforge", "test"], pkg, env=env)
    verdicts = {}
    for line in p.stdout.splitlines():
        m = re.match(r"\[(PASS|FAIL)\]\s+(\S+)", line.strip())
        if m:
            verdicts[m.group(2).split("::")[-1]] = "ok" if m.group(1) == "PASS" else "failed"
    if not verdicts:
        return None, secs, (p.stdout + p.stderr)[-2000:]
    return verdicts, secs, None


def artifact_digests(pkg):
    d = pkg / "target" / "dev"
    if not d.is_dir():
        return {}
    return {f.name: hashlib.sha256(f.read_bytes()).hexdigest() for f in sorted(d.glob("*.json"))}


def fresh_copy(pkg, suffix):
    """A new sibling directory with the package sources, so each tool builds from scratch."""
    dst = pkg.parent / f"{pkg.name}_{suffix}"
    (dst / "src").mkdir(parents=True)
    shutil.copy2(pkg / "Scarb.toml", dst / "Scarb.toml")
    shutil.copy2(pkg / "src" / "lib.cairo", dst / "src" / "lib.cairo")
    return dst


def build_parity(uc, pkg):
    uc_pkg = fresh_copy(pkg, "ucbuild")
    p, uc_secs = run([uc, "build"], uc_pkg)
    if p.returncode != 0:
        return {"error": "uc build failed: " + (p.stderr or p.stdout)[-1500:]}
    ucd = artifact_digests(uc_pkg)
    scarb_pkg = fresh_copy(pkg, "scarbbuild")
    env = dict(os.environ, SCARB_OFFLINE="true")
    p, scarb_secs = run(["scarb", "build"], scarb_pkg, env=env)
    if p.returncode != 0:
        return {"error": "scarb build failed: " + (p.stderr or p.stdout)[-1500:]}
    scd = artifact_digests(scarb_pkg)
    differ = sorted(k for k in set(ucd) | set(scd) if ucd.get(k) != scd.get(k))
    return {"artifacts": len(scd), "differ": differ, "uc_s": round(uc_secs, 2), "scarb_s": round(scarb_secs, 2)}


def prove_campaign(uc, out, rng, count):
    """u8 functions brute-forced over their whole domain. Helpers `h*` are called by the `p*`
    functions (inlining, callee panics); every function is checked."""
    pkg = out / "prove_pkg"
    (pkg / "src").mkdir(parents=True)
    (pkg / "Scarb.toml").write_text('[package]\nname = "prove_pkg"\nversion = "0.1.0"\nedition = "2024_07"\n\n[dependencies]\nstarknet = "2.18.0"\n')
    helpers = [Function(rng, f"h{i}", "u8", rng.randint(1, 2), max_depth=2) for i in range(max(4, count // 20))]
    functions = helpers + [Function(rng, f"p{i}", "u8", rng.randint(1, 2), helpers=helpers) for i in range(count)]
    (pkg / "src" / "lib.cairo").write_text("\n\n".join([prelude()] + [f.cairo() for f in functions]) + "\n")
    p, secs = run([uc, "prove", "--json", "--stateful-runs", "0"], pkg, timeout=3600)
    out_text = p.stdout
    try:
        rep = json.loads(out_text[out_text.index("{"):])
    except ValueError:
        return {"error": (p.stderr or p.stdout)[-2000:]}
    proofs = {pr["function"].split("::")[-1]: pr for pr in rep["packages"][0]["symbolic_proofs"]}
    count = len(functions)
    results = {"functions": count, "seconds": round(secs, 1), "status_counts": {}, "unsound": [], "false_cex": [], "missing": [], "panicking_functions": 0}
    for f in functions:
        domain = itertools.product(range(256), repeat=len(f.params))
        panics = [args for args in domain if f.outcome(args)[0] == "panic"]
        pr = proofs.get(f.name)
        if pr is None:
            results["missing"].append(f.name)
            continue
        st = pr["status"]
        results["status_counts"][st] = results["status_counts"].get(st, 0) + 1
        if panics:
            results["panicking_functions"] += 1
        if panics and st == "PROVEN_SAFE":
            results["unsound"].append({"function": f.name, "source": f.cairo(), "panicking_input": panics[0], "panic_inputs": len(panics)})
        if st == "COUNTEREXAMPLE_FOUND":
            ce = pr.get("counterexample") or {}
            try:
                args = tuple(int(ce[k]) for k in sorted(ce, key=lambda k: int(k.split("_")[-1]) if k.split("_")[-1].isdigit() else 0))[: len(f.params)]
            except (ValueError, KeyError):
                args = None
            if args is not None and len(args) == len(f.params) and all(0 <= a <= 255 for a in args):
                if f.outcome(args)[0] != "panic":
                    results["false_cex"].append({"function": f.name, "witness": args, "reason": pr.get("counterexample_reason"), "source": f.cairo(), "any_panic": bool(panics)})
    return results


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--uc", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--packages", type=int, default=2)
    ap.add_argument("--functions", type=int, default=20)
    ap.add_argument("--cases", type=int, default=6)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--snforge", action="store_true")
    ap.add_argument("--scarb", action="store_true")
    ap.add_argument("--prove", type=int, default=0)
    args = ap.parse_args()
    uc = str(Path(args.uc).resolve())
    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=False)
    rng = random.Random(args.seed)
    summary = {"seed": args.seed, "packages": [], "totals": {"cases": 0, "uc_disagree": 0, "snforge_disagree": 0, "uc_vs_snforge": 0, "build_differ": 0}}
    for pi in range(args.packages):
        name = f"arith_{args.seed}_{pi}"
        pkg = out / name
        functions, cases = [], []
        for fi in range(args.functions):
            ty = rng.choices(list(TYPES), weights=[4, 2, 2, 2, 1])[0]
            f = Function(rng, f"f{fi}", ty, rng.randint(1, 3), helpers=functions[-12:])
            functions.append(f)
            for ci in range(args.cases):
                a = tuple(rand_value(rng, ty) for _ in f.params)
                cases.append((f.name, ci, a, f.outcome(a), ty))
        write_package(pkg, name, functions, cases)
        expected = {f"t_{fn}_{ci}": ("ok", oc[0]) for (fn, ci, a, oc, ty) in cases}
        rec = {"package": name, "cases": len(cases), "panic_cases": sum(1 for c in cases if c[3][0] == "panic")}
        ucv, secs, err = uc_test_verdicts(uc, pkg)
        rec["uc_test_s"] = round(secs, 2)
        if ucv is None:
            rec["uc_error"] = err
        else:
            rec["uc_failed"] = sorted(t for t in expected if ucv.get(t) != "ok")
        if args.snforge:
            sv, ssecs, serr = snforge_verdicts(pkg)
            rec["snforge_s"] = round(ssecs, 2)
            if sv is None:
                rec["snforge_error"] = serr
            else:
                rec["snforge_failed"] = sorted(t for t in expected if sv.get(t) != "ok")
                if ucv is not None:
                    rec["uc_vs_snforge"] = sorted(t for t in expected if (ucv.get(t) == "ok") != (sv.get(t) == "ok"))
        if args.scarb:
            rec["build"] = build_parity(uc, pkg)
        t = summary["totals"]
        t["cases"] += len(cases)
        t["uc_disagree"] += len(rec.get("uc_failed", []))
        t["snforge_disagree"] += len(rec.get("snforge_failed", []))
        t["uc_vs_snforge"] += len(rec.get("uc_vs_snforge", []))
        t["build_differ"] += len((rec.get("build") or {}).get("differ", []))
        summary["packages"].append(rec)
        print(json.dumps({k: (v if not isinstance(v, list) else len(v)) for k, v in rec.items() if k not in ("uc_error", "snforge_error")}), flush=True)
        for k in ("uc_error", "snforge_error"):
            if k in rec:
                print(f"  {k}: {rec[k][:600]}", flush=True)
    if args.prove:
        summary["prove"] = prove_campaign(uc, out, rng, args.prove)
        pv = summary["prove"]
        print(json.dumps({k: (v if not isinstance(v, list) else len(v)) for k, v in pv.items()}), flush=True)
    (out / "summary.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary["totals"]), flush=True)


if __name__ == "__main__":
    main()
